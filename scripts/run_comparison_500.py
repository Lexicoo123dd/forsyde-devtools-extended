#!/usr/bin/env python3
import subprocess

print("=========================================================================")
print("BENCHMARK 1: SDF_example_036 (8-Channel Parallel Filterbank, 22 Actors)")
print("=========================================================================")
res_single = subprocess.run(["/tmp/bench_036_single", "500"], capture_output=True, text=True, check=True)
res_multi = subprocess.run(["/tmp/bench_036_multi", "500"], capture_output=True, text=True, check=True)
t1_36 = float(res_single.stdout.splitlines()[0].split(":")[1])
t8_36 = float(res_multi.stdout.splitlines()[0].split(":")[1])
out1_36 = int(res_single.stdout.splitlines()[1].split(":")[1])
out8_36 = int(res_multi.stdout.splitlines()[1].split(":")[1])
print(f"1 Core (PASS) Run-Time:         {t1_36:.4f} s")
print(f"8 Cores (PAPS Max) Run-Time:    {t8_36:.4f} s")
print(f"Measured Speedup (8 Cores):     {t1_36 / t8_36:.2f}x")
print(f"Theoretical Speedup Limit:      3.67x")
print(f"Efficiency vs Theoretical:      {(t1_36 / t8_36) / 3.67 * 100:.1f}%")
print(f"Bit-Exact Correctness:          {'PASS (Outputs match: ' + str(out1_36) + ')' if out1_36 == out8_36 else 'FAIL'}")

